package io.github.tavstaldev.portallock.models;

/**
 * Enum representing different types of fields in the PortalLock plugin.
 */
public enum EFieldType {
    /** Text field type. */
    TEXT,

    /** Number field type. */
    NUMBER,

    /** Boolean field type. */
    BOOLEAN,

    /** World key field type. */
    WORLD_KEY,

    /** Date and time field type. */
    DATETIME
}
